"""Turns the questions cut by scan_segment.py into a Supabase import (image-only questions with an answer key).

Each question becomes a closed question (qapali) whose text is EMPTY and whose image is the question itself; the options are
just the letters A-E. The code says where it comes from: KT<book>-S<section>-Q<number>, e.g. KT1-S01-Q030 (book 1, section 1,
question 30), so a reported code leads straight to the page.

Usage:
  python import_scans.py --dir scan/kimya_I_test --answers scan/kimya_I_bolme1_cavablar.json --book 1 --section 1 \
      --subject kimya --section-name "Ümumi kimya" --topic "Kimyanın əsas anlayışları" \
      --source-ref "Kimya test toplusu I (2025), bölmə 1" --year 2025 [--difficulty 3]
Output: out/import_kt<book>_s<section>.sql and the images (renamed to the code) in out/upload_kitab/.
Only questions that have an A-E answer in the key are included; the rest are listed.
"""
import argparse
import json
import re
import shutil
import sys
from pathlib import Path

from import_questions import lit

HERE = Path(__file__).parent
LETTERS = "ABCDE"


def build_sql(rows, a):
    values = ",\n".join(
        "  (" + ", ".join([lit(r["code"]), lit(r["image"]), lit(r["answer"])]) + ")" for r in rows
    )
    codes = ", ".join(lit(r["code"]) for r in rows)
    options = json.dumps({L: L for L in LETTERS})
    return f"""-- Generated by tools/dim/import_scans.py. {len(rows)} image-only questions: {a.source_ref}.
-- Run once in Supabase SQL Editor. Safe to re-run: the topic is created only if missing, questions are upserted by code.
-- Upload the images (out/upload_kitab/*.png) to the question-images bucket too.
set standard_conforming_strings = on;
begin;

do $$
begin
  if not exists (select 1 from subjects where slug = {lit(a.subject)}) then
    raise exception 'subjects cədvəlində slug={a.subject} yoxdur';
  end if;
  if not exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid
                  where t.typname = 'exam_level' and e.enumlabel = 'qebul') then
    raise exception 'exam_level enum-unda qebul etiketi yoxdur: import dayandırıldı';
  end if;
  if not exists (select 1 from pg_enum e join pg_type t on t.oid = e.enumtypid
                  where t.typname = 'question_type' and e.enumlabel = 'qapali') then
    raise exception 'question_type enum-unda qapali etiketi yoxdur: import dayandırıldı';
  end if;
end $$;

-- section and topic (only if missing)
insert into topics (subject_id, parent_id, name, sort_order)
select s.id, null, {lit(a.section_name)}, 50 from subjects s where s.slug = {lit(a.subject)}
on conflict (subject_id, parent_id, name) do nothing;

insert into topics (subject_id, parent_id, name, sort_order)
select s.id, p.id, {lit(a.topic)}, 50
  from subjects s join topics p on p.subject_id = s.id and p.parent_id is null and p.name = {lit(a.section_name)}
 where s.slug = {lit(a.subject)}
on conflict (subject_id, parent_id, name) do nothing;

insert into questions (code, topic_id, type, body, image_path, options, correct_answer, difficulty, solution,
                       exam_levels, groups, year, source, source_ref, is_active)
select v.code, t.id, 'qapali'::question_type, '', v.image_path, {lit(options)}::jsonb, v.correct,
       {a.difficulty}::smallint, null, array['qebul']::exam_level[], '{{}}'::smallint[], {a.year}::smallint, 'DİM',
       {lit(a.source_ref)} || ', sual ' || (regexp_match(v.code, 'Q(\\d+)$'))[1]::int, true
  from (values
{values}
       ) as v(code, image_path, correct)
  join subjects s on s.slug = {lit(a.subject)}
  join topics sec on sec.subject_id = s.id and sec.parent_id is null and sec.name = {lit(a.section_name)}
  join topics t on t.subject_id = s.id and t.parent_id = sec.id and t.name = {lit(a.topic)}
on conflict (code) do update set
  topic_id = excluded.topic_id, image_path = excluded.image_path, options = excluded.options,
  correct_answer = excluded.correct_answer, source_ref = excluded.source_ref, is_active = excluded.is_active;

do $$
declare n integer;
begin
  select count(*) into n from questions where code in ({codes});
  if n <> {len(rows)} then
    raise exception 'Gözlənilən {len(rows)} sual, bazada % tapıldı: geri alınır', n;
  end if;
end $$;

commit;

select count(*) as yuklenen_sual from questions where code like 'KT{a.book}-S{a.section:02d}-%';
"""


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", type=Path, required=True)
    ap.add_argument("--answers", type=Path, required=True)
    ap.add_argument("--book", type=int, required=True)
    ap.add_argument("--section", type=int, required=True)
    ap.add_argument("--subject", required=True)
    ap.add_argument("--section-name", required=True)
    ap.add_argument("--topic", required=True)
    ap.add_argument("--source-ref", required=True)
    ap.add_argument("--year", type=int, required=True)
    ap.add_argument("--difficulty", type=int, default=3)
    a = ap.parse_args()

    manifest = json.loads((a.dir / "manifest.json").read_text(encoding="utf-8"))
    key = json.loads(a.answers.read_text(encoding="utf-8"))["answers"]
    rows, skipped = [], []
    for q in sorted(manifest, key=lambda q: q["number"]):
        n = q["number"]
        answer = key.get(str(n))
        image = a.dir / q["file"]
        if answer not in list(LETTERS):
            skipped.append((n, "cavab açarında A-E yoxdur"))
        elif not image.exists():
            skipped.append((n, "şəkil faylı yoxdur"))
        else:
            rows.append({"code": f"KT{a.book}-S{a.section:02d}-Q{n:03d}", "image": f"KT{a.book}-S{a.section:02d}-Q{n:03d}.png",
                         "answer": answer, "src": image})
    if not rows:
        sys.exit("heç bir sual yüklənmir")
    assert all(re.fullmatch(r"KT\d+-S\d{2}-Q\d{3}", r["code"]) for r in rows)

    out_dir = HERE / "out" / "upload_kitab"
    out_dir.mkdir(parents=True, exist_ok=True)
    for r in rows:
        shutil.copy(r["src"], out_dir / r["image"])
    sql_path = HERE / "out" / f"import_kt{a.book}_s{a.section:02d}.sql"
    sql_path.write_text(build_sql(rows, a), encoding="utf-8")
    print(f"{len(rows)} sual -> {sql_path.name}; şəkillər -> {out_dir}")
    print(f"buraxılan {len(skipped)}: {skipped}")


if __name__ == "__main__":
    main()
